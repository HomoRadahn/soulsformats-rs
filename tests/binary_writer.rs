#[test]
#[should_panic]
fn already_reserved() {
    let mut writer = BinaryWriter::to_bytes(Endian::Big, false);
    writer.reserve_bool().unwrap();

    writer.seek(0).unwrap();
    writer.reserve_bool().unwrap();
}

